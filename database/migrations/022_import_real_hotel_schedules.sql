-- 1) Hotéis (um registro por hotel/passeio). Casamos o trip_id pelo slug.
--    Aviso: só entram slugs que EXISTEM na tabela trips.
INSERT INTO trip_hotels (trip_id, hotel_name, sort_order, is_active, created_at, updated_at)
SELECT t.id, s.hotel_name, MIN(s.sort_order), 1, NOW(), NOW()
FROM (SELECT DISTINCT trip_slug, hotel_name, sort_order FROM tmp_schedules) s
INNER JOIN trips t ON t.slug = s.trip_slug
GROUP BY t.id, s.hotel_name;

-- 2) Horários (um ou vários por hotel).
INSERT INTO trip_hotel_schedules (trip_hotel_id, pickup_time, is_active, created_at, updated_at)
SELECT th.id, s.pickup_time, 1, NOW(), NOW()
FROM tmp_schedules s
INNER JOIN trips t ON t.slug = s.trip_slug
INNER JOIN trip_hotels th ON th.trip_id = t.id AND th.hotel_name = s.hotel_name
GROUP BY th.id, s.pickup_time;

