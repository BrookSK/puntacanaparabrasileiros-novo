            <p>Esta Política de Privacidade descreve como a Punta Cana para Brasileiros coleta, utiliza, armazena e protege os dados das agências parceiras e de seus representantes no âmbito do Programa de Agências Parceiras. Ao se cadastrar como agência, o representante declara ter lido e aceitado esta Política.</p>

            <h2>1. Dados que Coletamos</h2>
            <p>Ao cadastrar sua agência, coletamos os dados fornecidos no formulário e durante o relacionamento comercial, tais como:</p>
            <ul>
                <li>Dados da empresa: razão social, nome fantasia, CNPJ/documento de registro, cidade e país;</li>
                <li>Dados de contato: nome do responsável, e-mail e telefone/WhatsApp;</li>
                <li>Dados de acesso: credenciais de login ao painel da agência;</li>
                <li>Dados financeiros para pagamento de comissões (quando aplicável);</li>
                <li>Dados de navegação e uso do painel (registros de acesso, endereço IP, páginas visitadas).</li>
            </ul>

            <h2>2. Como Utilizamos os Dados</h2>
            <p>Os dados da agência são utilizados para as seguintes finalidades:</p>
            <ul>
                <li>Analisar e aprovar a solicitação de cadastro da agência parceira;</li>
                <li>Liberar e gerenciar o acesso ao painel da agência;</li>
                <li>Calcular, registrar e efetuar o pagamento de comissões;</li>
                <li>Enviar comunicações operacionais, comerciais e de suporte;</li>
                <li>Prevenir fraudes e garantir a segurança da plataforma.</li>
            </ul>

            <h2>3. Base Legal</h2>
            <p>O tratamento dos dados ocorre com base na execução do contrato de parceria, no cumprimento de obrigações legais e regulatórias, no legítimo interesse da empresa e, quando exigido, no consentimento do titular, em conformidade com a Lei Geral de Proteção de Dados (Lei 13.709/18) e demais legislações aplicáveis.</p>

            <h2>4. Compartilhamento de Dados</h2>
            <p>A Punta Cana para Brasileiros não vende os dados das agências. O compartilhamento ocorre apenas quando necessário para a operação do programa, como com processadores de pagamento, provedores de tecnologia e autoridades competentes, sempre limitado ao estritamente necessário e mediante salvaguardas de segurança.</p>

            <h2>5. Armazenamento e Segurança</h2>
            <p>Adotamos medidas técnicas e administrativas para proteger os dados contra acessos não autorizados, perda, alteração ou divulgação indevida. Os dados são mantidos pelo tempo necessário ao cumprimento das finalidades descritas e das obrigações legais.</p>

            <h2>6. Direitos da Agência</h2>
            <p>O representante da agência pode, a qualquer momento, solicitar o acesso, a correção, a atualização ou a exclusão de seus dados pessoais, bem como informações sobre o tratamento realizado, mediante contato pelos canais oficiais da empresa.</p>

            <h2>7. Encerramento da Parceria</h2>
            <p>Em caso de encerramento da parceria, os dados poderão ser mantidos pelo período necessário ao cumprimento de obrigações legais, fiscais e de auditoria, sendo posteriormente eliminados ou anonimizados.</p>

            <h2>8. Alterações desta Política</h2>
            <p>Esta Política poderá ser atualizada a qualquer momento em razão de mudanças legais ou operacionais. Recomendamos que a agência a consulte periodicamente.</p>

            <h2>9. Contato</h2>
