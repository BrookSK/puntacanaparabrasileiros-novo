            <li>Entre 48h e 24h antes do passeio: <strong>reembolso de 50%</strong>.</li>
            <li>Com menos de 24h de antecedência ou em caso de não comparecimento (no show): <strong>sem reembolso</strong>.</li>
            <li>Em situações de emergência comprovada (como problemas de saúde ou cancelamento de voo), a solicitação será analisada individualmente. É necessário o envio de documentação que comprove o motivo.</li>
        </ul>

